const ERROR_MESSAGES: Record<number, string> = {
  400: 'Некорректный запрос. Проверьте данные и повторите попытку.',
  401: 'Сессия истекла. Пожалуйста, войдите снова.',
  403: 'Доступ запрещён. Недостаточно прав для выполнения операции.',
  404: 'Запрашиваемый ресурс не найден.',
  409: 'Конфликт данных. Запись уже существует.',
  422: 'Неверный формат данных. Проверьте введённые данные.',
  500: 'Внутренняя ошибка сервера. Попробуйте позже.',
  502: 'Сервер временно недоступен. Попробуйте позже.',
  503: 'Сервис недоступен. Попробуйте позже.',
}

export const showErrorAlert = (status: number): void => {
  const message = ERROR_MESSAGES[status] ?? 'Непредвиденная ошибка сервера. Попробуйте позже.'
  alert(`Ошибка ${status}\n${message}`)
}
