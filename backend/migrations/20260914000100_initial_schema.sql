CREATE SCHEMA auth;
CREATE SCHEMA submissions;
CREATE SCHEMA events;
CREATE SCHEMA notifications;

CREATE TYPE auth.admin_role AS ENUM ('super_admin', 'admin');
CREATE TYPE submissions.submission_status AS ENUM ('processing', 'new', 'review', 'rejected', 'published');

CREATE TABLE auth.admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role auth.admin_role NOT NULL DEFAULT 'admin',
    email VARCHAR(255) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE submissions.submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    event_date DATE NOT NULL,
    event_type_code TEXT NOT NULL CHECK (event_type_code IN ('political', 'military')),
    email VARCHAR(254) NOT NULL,
    telegram_username VARCHAR(100) NOT NULL,
    archive_id VARCHAR(200) NOT NULL,
    site_url VARCHAR(500),
    screenshot_url VARCHAR(500),
    slug VARCHAR(255) NOT NULL UNIQUE,
    status submissions.submission_status NOT NULL DEFAULT 'processing',
    admin_comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX submissions_email_idx ON submissions.submissions (LOWER(email));
CREATE INDEX submissions_status_idx ON submissions.submissions (status);
CREATE INDEX submissions_event_type_code_idx ON submissions.submissions (event_type_code);

CREATE TABLE submissions.audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL REFERENCES submissions.submissions (id) ON DELETE CASCADE,
    admin_login VARCHAR(100) NOT NULL,
    admin_role VARCHAR(50) NOT NULL,
    action VARCHAR(50) NOT NULL,
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX audit_log_submission_id_idx ON submissions.audit_log (submission_id);

CREATE TABLE events.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL UNIQUE,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    event_date DATE NOT NULL,
    event_type_code TEXT NOT NULL CHECK (event_type_code IN ('political', 'military')),
    site_url VARCHAR(500) NOT NULL,
    preview_image_url VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX events_event_type_code_idx ON events.events (event_type_code);
CREATE INDEX events_event_date_idx ON events.events (event_date);

CREATE TABLE notifications.deliveries (
    event_key TEXT NOT NULL CHECK (length(event_key) BETWEEN 1 AND 200),
    channel TEXT NOT NULL CHECK (channel IN ('email', 'telegram')),
    status TEXT NOT NULL CHECK (status IN ('processing', 'sent', 'failed')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error TEXT NOT NULL DEFAULT '' CHECK (length(last_error) <= 500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    delivered_at TIMESTAMPTZ,
    PRIMARY KEY (event_key, channel)
);

