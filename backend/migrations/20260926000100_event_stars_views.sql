-- Звезда события: одна на пользователя, рейтинг - число строк. Ограничение держит первичный ключ.
CREATE TABLE events.stars (
    event_id BIGINT NOT NULL REFERENCES events.events (id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users.users (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (event_id, user_id)
);

-- Просмотр сайта события на странице /event/:id. Каждое открытие - строка. Автор берётся через
-- events.submission_id -> заявка, почту здесь не храним. visitor_id - случайный id браузера:
-- по нему считаются уникальные гости и проверяется, что длительность дописывает тот же посетитель.
CREATE TABLE events.views (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events.events (id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES users.users (id) ON DELETE SET NULL,
    visitor_id UUID NOT NULL,
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    active_seconds INTEGER NOT NULL DEFAULT 0 CHECK (active_seconds BETWEEN 0 AND 7200)
);

CREATE INDEX views_event_id_idx ON events.views (event_id);

