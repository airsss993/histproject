-- Как далеко посетитель долистал сайт события, в процентах высоты страницы. Присылает скрипт,
-- который worker дописывает в HTML сайта.
ALTER TABLE events.views
    ADD COLUMN scroll_percent SMALLINT NOT NULL DEFAULT 0 CHECK (scroll_percent BETWEEN 0 AND 100);

-- Действия посетителей для метрик панели: открытие карточки события на карте, переход из неё на сайт,
-- шаги формы заявки. event_id без внешнего ключа: схема своя, а строка переживает снятое событие.
CREATE SCHEMA metrics;

CREATE TABLE metrics.actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action TEXT NOT NULL CHECK (action IN ('card_open', 'card_click', 'form_step')),
    event_id BIGINT,
    step SMALLINT CHECK (step BETWEEN 0 AND 20),
    visitor_id UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX actions_created_at_idx ON metrics.actions (created_at);

